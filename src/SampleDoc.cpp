#include "SampleDoc.h"

using namespace std;
using namespace PoDoFo;

void pdfsign::BuildSampleDocument(PdfMemDocument& doc)
{
    auto& page = doc.GetPages().CreatePage(PdfPageSize::A4);

    auto& bold = doc.GetFonts().GetStandard14Font(PdfStandard14FontType::HelveticaBold);
    auto& regular = doc.GetFonts().GetStandard14Font(PdfStandard14FontType::Helvetica);

    PdfPainter painter;
    painter.SetCanvas(page);

    painter.GraphicsState.SetNonStrokingColor(PdfColor(0.1));
    painter.TextState.SetFont(bold, 20.0);
    painter.DrawText("Sample document", 56.0, 760.0);

    painter.TextState.SetFont(regular, 11.0);
    painter.DrawText("Generated by podofo-pdf-sign so there is something to sign.",
        56.0, 735.0);

    const char* lines[] = {
        "This page exists only to carry a signature. Everything interesting",
        "happens in the PDF structure rather than on the page: a signature",
        "field is added to the AcroForm, a byte range covering the whole file",
        "is hashed, and a detached CMS blob over that hash is embedded in the",
        "signature dictionary.",
        "",
        "Pass --in to sign a real document instead of this one.",
    };

    auto y = 700.0;
    for (auto line : lines)
    {
        painter.DrawText(line, 56.0, y);
        y -= 16.0;
    }

    painter.FinishDrawing();
}
